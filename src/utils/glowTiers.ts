// ★光の大きさの台帳(社長指示 v0.25.2808「まとめよう」)。
//
// それまで `spawnGlow(x, y, <生の数字>, ...)` の第3引数が **20種類以上バラバラ**に散らばっていて、
// 「どれが強い光なのか」がコードからも実機からも読めなかった。**6段に丸めて1箇所で持つ。**
//
// ★基準は **手榴弾の爆発 = 44**(`STRONG_GLOW_RADIUS` と同値)。これ未満の光は
// 影にも地面の光だまりにも**一切参加しない**ので、段には入れない(=丸め対象外)。
//
// 実測(v0.25.2807 の全走査)で、44以上の光は 44/46/50/54/56/58/62/68/70/72/78/88/95/96/130/140/150 の17種類。
// これを近いもの同士で6段に寄せた。**倍率は基準44に対する比**。

/** 段1: 手榴弾の爆発(基準・1.00倍)。踏み潰し/ヘビーグレネードもここ。 */
export const GLOW_R_XS = 44;
/** 段2: 1.27倍。地雷・小爆発/プロップ破壊/被弾/近接トドメ/グレネードランチャー/店の反応。 */
export const GLOW_R_S = 56;
/** 段3: 1.59倍。クエストNPC/叫喚の溜め/商人/スケボー/回復。 */
export const GLOW_R_M = 70;
/** 段4: 2.05倍。レベルアップの芯/★カウンター成功(戦闘中いちばん頻出)/死亡/裏ボス討伐。 */
export const GLOW_R_L = 90;
/** 段5: 2.95倍。レベルアップ/ボス被弾スタン/叫喚の本番。 */
export const GLOW_R_XL = 130;
/** 段6: 3.41倍。城ボス出現/召喚/ボス撃破。 */
export const GLOW_R_XXL = 150;

/** 6段の一覧(昇順)。 */
export const GLOW_TIERS = [GLOW_R_XS, GLOW_R_S, GLOW_R_M, GLOW_R_L, GLOW_R_XL, GLOW_R_XXL] as const;

/**
 * 計算で出た半径を**一番近い段へ丸める**。
 * 救急鞄(`爆発半径 × 0.55`)やファイアナイフ(`爆発半径 × 0.68`)のように
 * **可変で決まる光**を段に乗せるためのもの。
 *
 * ★段の下(44未満)は**丸めない**。そこは「影にも地面にも効かない小さな光」で、
 * 引き上げると**戦闘中ずっと地面が光る**ことになるため(意図的に段の外へ置いている)。
 */
export const snapGlowRadius = (radius: number): number => {
  if (!(radius >= GLOW_R_XS)) return radius; // 閾値未満はそのまま(NaNもそのまま返す=呼び側の値を壊さない)
  let best: number = GLOW_TIERS[0];
  let bestDiff = Infinity;
  for (const t of GLOW_TIERS) {
    const d = Math.abs(radius - t);
    // ★同点なら**大きい方**へ寄せる(段は昇順なので `<=` で後勝ち)。
    // 例: 50 は 44 とも 56 とも距離6。切り下げると光が痩せるので、迷ったら大きい側に倒す
    // (CLAUDE.md「迷ったら派手側に倒す」)。
    if (d <= bestDiff) { bestDiff = d; best = t; }
  }
  return best;
};
