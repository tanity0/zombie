// ★★シートのコマを「立ち絵と同じ背丈」で出すための補正(社長指示2026-09-24「**倍率入れて**」)。
//
// ★何が起きていたか: 絵は `containScale`(=`min(枠W/絵W, 枠H/絵H)`)で枠に内接させている。
// **枠は当たり判定から決まる固定の矩形**なので、**絵の縦横比が変わると内接倍率が変わり、背丈も変わる**。
// アニメーションのコマは**立ち絵と比率が違う**(腕を振る・武器を伸ばす・脚を開くと横が広くなる)ので、
// **動き出した瞬間に背丈が変わる**——実測で **-10%〜+9.2%** の幅があった(2026-09-24・全30シート)。
//
// | 立ち絵 | シート | ずれ |
// |---|---|---|
// | リッチ | 歩き | **-10.0%** |
// | 骸骨(女) | 攻撃 | **+9.2%** |
// | ステージ3の城ボス | 歩き | **-8.9%** |
// | 蜘蛛 | 跳ぶ | -8.0% |
// | ハンター | 跳ぶ | -7.1% |
// | リッチ | 攻撃 | -3.3% / 伐採人の薙ぎ +3.1% / 削岩型の突き +2.1% / ハンターの歩き -1.9% / 自転車の歩き +1.5% |
//
// ★**表は作らない。** 「どのシートが何%ずれるか」を人が書き写すと、素材が差し替わるたびに嘘になる。
// **立ち絵とコマの実寸から毎フレーム出す**=素材を差し替えても、シートを足しても、自動で合う。
//
// ★**判定は1pxも動かない**(これは描画倍率だけ)。`enemyHitStrip` は**立ち絵の縦横比**を見ているので、
// むしろ**見た目と判定が近づく**。接地影は実スプライト幅から出しているので一緒に付いてくる。

/**
 * シートのコマを立ち絵と同じ背丈にする倍率。`1` = 補正なし。
 *
 * @param boxW/boxH 枠(当たり判定 × 視覚倍率)。立ち絵とコマで同じものを渡すこと。
 * @param idleW/idleH 立ち絵のテクスチャ寸法
 * @param sheetW/sheetH **コマ1枚**のテクスチャ寸法(シート全体の幅ではない)
 */
export const sheetHeightFix = (
  boxW: number, boxH: number,
  idleW: number, idleH: number,
  sheetW: number, sheetH: number,
): number => {
  if (!(boxW > 0 && boxH > 0 && idleW > 0 && idleH > 0 && sheetW > 0 && sheetH > 0)) return 1;
  const idleDrawn = Math.min(boxW / idleW, boxH / idleH) * idleH;
  const sheetDrawn = Math.min(boxW / sheetW, boxH / sheetH) * sheetH;
  return sheetDrawn > 0 && Number.isFinite(idleDrawn / sheetDrawn) ? idleDrawn / sheetDrawn : 1;
};
