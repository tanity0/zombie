// 近接ヒットの炸裂(社長支給の実写VFX・2026-09-16「VFXの試し1つ。近接当てた時用」)。
//
// 素材: ActionVFX "Spell Hit 3"(ProRes 2048×1080 / 24fps / 2.33秒)。
// **使えるのは最初の15コマだけ**——実測で、明るさは3コマ目に頂点を打ち、
// 20コマ目には最大値が150、39コマ目以降は**全画素ゼロ**(=何も映っていない尺が1.5秒ある)。
// そこで 3〜17コマ目を切り出し、効果の外接矩形(元寸 674px角)を 720px角で囲って 176px へ縮めた。
//
// ★焼き直し(2026-09-16・社長報告「出てるけど、真っ暗でよく見えない。影みたいなの」):
// 初版は**元の暗さをそのまま持ち込んでいた**(可視部のRGB平均 0.49 / α平均 0.11 =
// 加算で足す量が画面の5%しかない)。しかも元素材は**黒背景**なので、何かの理由で加算合成が
// 効かない経路に落ちると「黒い塊=影」に見える。そこで焼き方を変えた:
//   ①**RGBは色相だけ残して明度を1.0へ**正規化し、さらに白へ50%寄せる(可視部のRGB平均 0.88)
//   ②**αは明るさの0.6乗**(中間調が消えないように太らせる。α平均 0.11→0.20)
// 結果、加算で足す量が約3.5倍になり、**通常合成に落ちても白い閃光として読める**
// (=「影に見える」という壊れ方が原理的に起きない)。縮小はプリマルチプライしてから行う。
export const MELEE_HIT_FRAMES = 15;
/** 近接は手数が多いので短く。ただし社長報告「VFX出てない」を受けて 340→420ms(約36fps)へ。
 *  340msは実機で気づけなかった=「小さくて見えない=存在しないのと同じ」側に寄っていた。 */
export const MELEE_HIT_MS = 420;

/** 進行度 t(0..1)→ コマ番号。端は丸める。 */
export const meleeHitFrame = (t: number): number =>
  Math.min(MELEE_HIT_FRAMES - 1, Math.max(0, Math.floor(t * MELEE_HIT_FRAMES)));

/** コマ番号 → テクスチャ名。 */
export const meleeHitTexture = (frame: number): string =>
  `fx/melee-hit-${String(Math.min(MELEE_HIT_FRAMES - 1, Math.max(0, frame))).padStart(2, '0')}`;
