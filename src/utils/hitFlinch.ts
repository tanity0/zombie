import type { EnemyType } from '../types/game';
import { isBossType } from './enemyUtils';

/**
 * ★被弾リアクションの強さを、そのヒットのダメージから決める**1本の数**
 * (社長指示2026-09-17「**のけぞりとノックバックは連動。さらに停止時間もそれによって長く設けるなど
 * したい**」/「**のけぞりは下限を決めたい。体感あるくらいののけぞりを下限にして、そこから計算**」)。
 *
 * ★何が壊れていたか(2026-09-17の実測):
 * 1. **掛かっていたのは「しなり」だけ**だった。同じ被弾で出る**跳ね・白フラッシュ・被弾の光**は
 *    量を見ておらず満額。⇒ 雑魚でもしなりだけ弱まり、残り3つが満額で出るので
 *    「**延焼でも常にのけぞって見える**」(社長報告)。
 * 2. **強個体・ボスは式の対象外=いつでも満額**だった。延焼の1tickでも満額でのけぞっていた。
 * 3. **満額になる閾値(最大HPの15%)が高すぎた。** 敵の実効HPは `ENEMY_HP_MULT=5` 倍が掛かるので
 *    ゾンビは実効200前後。ハンドガン1発=9ダメージは **4.5%** しかなく、旧式では **下限(0.15)に
 *    張り付いていた**。⇒ **普通の一発も延焼の1tickも、同じ「ほぼ無反応」**になっていた。
 *    下限0.15はしなり角にして **約5度=実質見えない**。社長の「体感あるくらいの下限」はここを指す。
 *
 * ★直し方: **下限を"かろうじて分かる"所に置き、満額の閾値を実際の火力に合わせて下げる。**
 * そのうえで **1つの数**を のけぞり/跳ね/フラッシュ/光/ノックバック/停止時間 の**全部**が読む。
 */

/**
 * 満額になるダメージ(最大HPに対する割合)。
 * ★15%→**6%**(2026-09-17)。15%は実効HPに対して非現実的で、ほぼ全ての一発が下限に落ちていた。
 * 6%なら: 延焼1tick(5/200)=2.5% → 0.42 / ハンドガン(9/200)=4.5% → 0.75 /
 * クロスボウ(24)・ハンドキャノン(31)=満額。**普通の一発と持続ダメージに実際の差が出る。**
 */
export const FLINCH_FULL_DAMAGE_FRAC = 0.06;
/**
 * ★強個体・ボスの満額の閾値。**除外(いつでも満額)をやめた**代わりに、こちらを下げる。
 * この層は最大HPが桁違い(パンプキン750・城ボス2500〜)なので、雑魚と同じ6%では
 * どんな一発も下限に張り付く。**2%**なら:
 *   強個体(750): ハンドガン(9)=0.60 / ハンドキャノン(31)=満額 / 延焼1tick(5)=下限
 *   城ボス(2500): ハンドガン=下限 / ハンドキャノン=0.62 / 延焼1tick=下限
 * ⇒ **強個体は雑魚より反応が鈍い**(大きく重い体なので正しい)一方、
 *   **重い一発はちゃんと満額**で、**延焼の1tickだけが下限へ落ちる**(これが狙い)。
 */
export const FLINCH_FULL_DAMAGE_FRAC_BOSS = 0.02;

/**
 * ★下限(社長指示「**体感あるくらいののけぞりを下限にして**」)。0.15→**0.30**。
 * しなりの満額は `ENEMY_HIT_FLINCH_SKEW=0.58rad`(約33度)なので、
 * **0.30 ≒ 10度**=「かろうじて分かる」。0.15(約5度)は見えなかった。
 * ★"快適な"のけぞりではなく **"最小で認識できる"のけぞり**を置く(ここから上へ計算するため)。
 */
export const FLINCH_MIN_STRENGTH = 0.30;

/**
 * ★**ダメージの絶対量**でも頭打ちにする(2026-09-17・実機で測って足した軸)。
 *
 * 割合(最大HPに対する%)だけで見ると、**小さい敵ほど何をされても満額**になる——実測では
 * **コウモリ(実効HP40)は延焼の1tick(5)でも満額(33度)**でのけぞった。
 * これでは社長の「**延焼でも敵が常にのけぞってる**」が小型の敵で直らない。
 *
 * ⇒ **割合と絶対量の小さい方**を採る。意味はエルデンリングの「体勢(ポイズ)」に近い:
 * **軽い一撃は誰に当てても軽い**(絶対量の軸)/ **巨体は同じ一撃でも動じない**(割合の軸)。
 * 満額になる絶対量は**14**(=序盤の近接=ハチェット1振り)。
 *   延焼1tick(5)=0.36 / ショットガン1粒(6)=0.43 / ハンドガン(9)=0.64 / ハチェット(14)以上=満額。
 * 強化が進んで火力が上がれば自然に満額へ寄る(=強くなったぶん手応えも重くなる)。
 */
export const FLINCH_FULL_DAMAGE_ABS = 14;

/**
 * ダメージ量 → リアクションの強さ(0〜1)。`damage` が未記録(まだ1度も殴られていない個体など)は
 * 従来どおり満額の1を返す=情報が無い時に弱める、という賭けをしない。
 */
export const hitReactionStrength = (
  damage: number | undefined, maxHealth: number, fullFrac = FLINCH_FULL_DAMAGE_FRAC,
): number => {
  if (damage === undefined) return 1;
  const dmg = Math.max(0, damage);
  const byFrac = (dmg / Math.max(1, maxHealth)) / fullFrac;   // 巨体は動じない
  const byAbs = dmg / FLINCH_FULL_DAMAGE_ABS;                 // 軽い一撃は誰に当てても軽い
  return Math.min(1, Math.max(FLINCH_MIN_STRENGTH, Math.min(byFrac, byAbs)));
};

/** 敵1体ぶんの判定。**描画・ノックバック・停止時間の唯一の窓口**。 */
export const enemyHitReaction = (
  e: { type: EnemyType; lastHitDmg?: number; maxHealth: number },
): number => hitReactionStrength(
  e.lastHitDmg, e.maxHealth,
  isBossType(e.type) ? FLINCH_FULL_DAMAGE_FRAC_BOSS : FLINCH_FULL_DAMAGE_FRAC,
);

/**
 * ★1つの強さ `r` を、反応ごとの倍率へ写す表。
 *
 * **基準点は「ハンドガン1発 = r≒0.64」で、そこが今と同じ手応えになるように置いた。**
 * 素直に `×r` すると**全部が今より弱くなる**(社長は以前「吹き飛ばなくなった?」と指摘済み)。
 * ⇒ **今の普通の一発を1.0に合わせ、下は落とし、上は伸ばす**。
 *
 * | 反応 | 下限(0.30) | 延焼1tick(0.36) | 散弾1粒(0.43) | **ハンドガン(0.64)** | 満額(1.0) |
 * |---|---|---|---|---|---|
 * | のけぞり | 0.30 | 0.36 | 0.43 | **0.64** | 1.00 |
 * | 跳ね | 0.71 | 0.76 | 0.82 | **1.00** | 1.30 |
 * | 白フラッシュ・被弾の光 | 0.79 | 0.83 | 0.87 | **1.00** | 1.00 |
 * | ノックバックの速さ | 0.86 | 0.88 | 0.91 | **1.00** | 1.15 |
 * | ノックバックの時間 | 0.93 | 0.94 | 0.96 | **1.00** | 1.07 |
 * | **停止時間** | 0.96 | 1.01 | 1.07 | **1.25** | **1.55** |
 *
 * ★**停止時間だけ上へ大きく伸ばす**(社長「**停止時間もそれによって長く設けるなど**」)。
 * 重い一発ほど画面が止まる=手応えの本体。のけぞりだけ `×r` の素通しなのは、
 * **しなりは0から始まってよい**(浅いしなりも「効いた」には見える)ため。
 */
export const flinchMul = (r: number): number => r;
export const hopMul = (r: number): number => 0.45 + 0.85 * r;
export const flashMul = (r: number): number => Math.min(1, 0.61 + 0.6 * r);
export const knockbackSpeedMul = (r: number): number => 0.73 + 0.42 * r;
export const knockbackDurationMul = (r: number): number => 0.87 + 0.20 * r;
export const hitStopMul = (r: number): number => 0.71 + 0.84 * r;
