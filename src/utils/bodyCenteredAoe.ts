// 「足元の円AoE」= **ボス自身の中心に出る円**の判定半径。v0.25.2612・社長指示「ミーミルは直して /
// そして二度と起きない学習」。
//
// 事故(社長報告):「ミーミルの牙がミーミルの中心に発動するので当たりっこないです」
//   ミーミルの当たり判定は **248×138(半幅124)**。牙の判定は **半径92**、発生点は**本体の中心**。
//   ⇒ **92 < 124** なので円が体の中に収まる。プレイヤーは体にぶつかるので必ず124px以上外側に居る。
//   ⇒ **左右から挑む限り構造的に一度も当たらない技**だった。
//
// 原因は値そのものではなく **「体の大きさを見ずに他所から流用した」**こと:
//   `MIMIR_BITE_RADIUS = GRENADE_BLAST_RADIUS(92)` は城ボス(giantbat **60×60**)の系譜の値。
//   同じ「足元の円」でも城ボスの踏み鳴らしは **半径130 vs 半幅30 = 体の外へ100px** 届いている。
//   体が4倍大きいミーミルに92をそのまま持ってきたので、符号が逆になった。
//
// **二度と起こさないための不変条件**(`bodyCenteredAoe.test.ts` で機械検証):
//   > 足元の円AoEは、**そのボスの当たり判定の外へ最低 MIN_BODY_AOE_REACH_PX 届かなければならない**。
//   > 届く距離 = 半径 − max(width, height) / 2
//   新しく足元の円AoEを足す時は、**このファイルの表(BODY_CENTERED_AOES)に必ず登録する**こと。
//   登録すればテストが自動で検算する。**登録を忘れた技は守られない**ので、そこだけは人が守る。
//
// ※対象は「本体の中心に出る円」だけ。着地点に出る円(トール/ラフィのジャンプ)や、本体から
//   相手へ伸びるカプセル(ヨルムンガンドの薙ぎ・アイドルの殴り)は**発生点が体の外**なのでこの罠は無い。
import { ENEMY_STATS } from './enemyUtils';
import type { EnemyType } from '../types/game';

/**
 * ミーミル「群体の噛みつき」(§6.28-5/§6.28-15)の判定半径。
 * v0.25.2612(社長指示「直して」): **92 → 216**。
 * 根拠=城ボスの踏み鳴らしと同じ理屈に揃えた: 半幅124 + 体外リーチ92(城ボスは 30 + 100)。
 * 旧値92は `GRENADE_BLAST_RADIUS`(社長裁定6.26-9 #3)からの流用だったが、**体の大きさが4倍違う**ため
 * そのままでは成立しなかった(上の事故メモ)。**リーチの考え方を揃えた値**であって、
 * 「強くしたかったから上げた」のではない。
 */
export const MIMIR_BITE_RADIUS = 216;

/** 足元の円AoEが体の外へ届くべき最小距離(px)。これ未満は「当てる気が無い判定」とみなす。 */
export const MIN_BODY_AOE_REACH_PX = 40;

/** 足元の円AoE1件ぶんの登録。新しく足したらここに追加する(テストが自動で検算する)。 */
export interface BodyCenteredAoe {
  /** 表示用の技名(テストの失敗メッセージに出る)。 */
  label: string;
  /** 技を出すボスの型。 */
  owner: EnemyType;
  /** 判定半径(px)。 */
  radius: number;
}

/**
 * 純関数: その円が**体の外へ何px届くか**。負なら体の中に収まっている=当たらない。
 * 「max(width, height)/2」を使うのは、**どの向きから挑んでも届く**ことを保証するため
 * (幅248・高さ138のミーミルなら、横から来た人が一番遠い=124が基準になる)。
 */
export const bodyAoeReachPx = (owner: EnemyType, radius: number): number => {
  const s = ENEMY_STATS[owner];
  if (!s) return radius; // 未知の型は検算対象外(テスト側で存在を別途担保する)
  return radius - Math.max(s.width, s.height) / 2;
};

/** 純関数: その円は「当てる気のある判定」か(不変条件そのもの)。 */
export const bodyAoeReaches = (owner: EnemyType, radius: number): boolean =>
  bodyAoeReachPx(owner, radius) >= MIN_BODY_AOE_REACH_PX;
