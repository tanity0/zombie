/** 帯の半幅(判定半径に対する比)。叩き台=実機で社長が決める(`?csweepw=` で上書き)。 */
export const CIRCLE_SWEEP_HALF_W = 0.34;

/**
 * 帯の濃さの倍率(現行の据え置き円の塗りα=0.098 に対して掛ける)。
 *
 * **★v0.25.4093 で新設**: 初版は現行の塗りαをそのまま上限にしていたため、
 * **帯が事実上見えなかった**(0.098 は「円全体を薄く塗る」ための値で、
 * 面積が1/3以下の帯に使うと画面に出ない)。
 * 既定 2.5 = **v0.25.3093 の減光(`TELEGRAPH_FILL_MULT`=0.4)を掛ける前の濃さに戻す**値。
 * 帯の面積は円全体の6割弱・平均濃度はピークの約半分なので、
 * **画面に乗る赤の総量は現行の据え置き円より少ないまま**(=「予告の赤を薄くしたい」に反しない)。
 * `?csweepa=` で上書き。
 */
export const CIRCLE_SWEEP_ALPHA_MULT = 2.5;

/** 帯を刻む段数(濃度のグラデをこの本数のリングで作る)。 */
export const CIRCLE_SWEEP_STEPS = 14;

/**
 * 帯の中心半径。`prog` 0→1 で **R → −halfW** へ動く
 * (= 外枠に乗った状態で始まり、中心を通り抜けて消え切る)。
 *
 * **★v0.25.4093 の訂正**: 初版は `R+halfW` から始めていたため、**溜めの最初の2割は帯が円の外に居て
 * 画面に何も出なかった**(予告が出ていないのと同じ)。**外枠から始める**=1フレーム目から
 * 「どこが危ないか」が出る。フェードは帯の**内側の縁**が担う。
 *
 * **等速にしない**(CLAUDE.md「動きの絶対ルール: 慣性」)。ease-in(だんだん速くなる)を掛けてあり、
 * 溜めの序盤は外周付近に留まって危険域を見せ、終盤で内側へ加速して消え切る
 * =**消え切る瞬間が立つ**。`ease=false` で等速(ロールバック用)。
 */
export const circleSweepBand = (prog: number, radius: number, halfW: number, ease = true): number => {
  const t = Math.max(0, Math.min(1, prog));
  const e = ease ? t * t : t;
  return radius - e * (radius + halfW);
};

/**
 * 半径 `r` の位置での帯の濃さ(0〜1)。中心で1、両縁へ向かってフェードして0になる(=グラデ)。
 * これを円の絵のアルファに掛ける=マスク。
 */
export const circleSweepAlphaAt = (r: number, band: number, halfW: number): number => {
  if (halfW <= 0) return 0;
  const d = Math.abs(r - band) / halfW;
  if (d >= 1) return 0;
  const t = 1 - d;
  return t * t * (3 - 2 * t); // smoothstep=縁が硬く切れない
};
