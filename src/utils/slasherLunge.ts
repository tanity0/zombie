/**
 * スラッシャー(連続攻撃スキル)の追撃で、押した敵へ「自動追尾」する踏み込み距離。
 *
 * ★社長発案 v0.25.3540:
 *   「スラッシャーは射程内であれば、その敵から規定の距離(近接入る距離)まで自動追尾
 *     であれば事故が減りそう」
 *   「追撃の範囲は、自分がいま立ってるところからの近接攻撃射程内。じゃないと射程が嘘になるので」
 *
 * なぜ純関数に切り出したか(実装精度の規律4): 旧実装は**踏み込み20px固定**なのに**強制KBは25px**
 * (Lv3最終段は50px)で、**数字が2本あった**。押し量を変えるたびにズレが再発する構造で、実際に
 * 毎撃5pxずつ相手が逃げていた(v0.25.3538の洗い出しで発覚)。定数を突き合わせる設計をやめ、
 * **押し量から毎回算出する**ことでこの事故の型そのものを消す。式をここに置いてテストで固定する。
 *
 * 考え方:
 *   踏み込み = (いま押した後の敵までの距離) − (近接が入る距離)
 *   ・「押した後の距離」は予測値。ノックバックは速度で280msかけて効くため、この一撃を打った瞬間の
 *     敵はまだ動いていない=実測では取れない。自分が与えた押し量は分かっているので足して予測する。
 *   ・「近接が入る距離」は射程そのものではなく、わずかに内側(STANDOFF_FRAC)。境界ちょうどに
 *     着地すると次フレームの揺らぎで空振りしうるため。
 *   ・結果が負(押しても射程内に残る)なら踏み込まない=0。押し量がいくつでも、将来ノックバック
 *     減衰が入って変わっても、**常に近接が入る位置に着地する**。
 */

/** 踏み込みの安全上限(px)。押し量の最大(Lv3最終段=50px)を拾える最小値。叩き台。 */
export const SLASHER_LUNGE_MAX_PX = 60;
/** 着地位置 = 近接射程の何割の距離か。境界ちょうどを避けるためわずかに内側。叩き台。 */
export const SLASHER_LUNGE_STANDOFF_FRAC = 0.9;

/**
 * @param distToTarget 追撃を当てた時点での敵までの距離(`enemyMeleeDist` と同じ「判定帯の最近点まで」)
 * @param pushedPx     この一撃でその敵を押した実距離(px)
 * @param meleeRange   いまの近接射程
 * @returns 踏み込む距離(px)。0 なら踏み込まない。
 */
export const slasherLungePx = (
  distToTarget: number,
  pushedPx: number,
  meleeRange: number,
): number => {
  const standoff = meleeRange * SLASHER_LUNGE_STANDOFF_FRAC;
  return Math.max(0, Math.min(SLASHER_LUNGE_MAX_PX, distToTarget + pushedPx - standoff));
};
