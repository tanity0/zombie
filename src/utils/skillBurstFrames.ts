// スキル取得の炸裂(社長支給の実写VFX・2026-09-16「スキル取得時のエフェクト用VFX素材これで」)。
//
// 素材: ActionVFX "Spell Hit Side 4"(ProRes 2048×1080 / 24fps / 1.5秒)。
// **使うのは 2〜14コマ目の13コマ**——14コマ目より後は被覆率が 0.1パーセントを切り、
// 尺だけ食って**何も映っていない枠を掴んでいる**(クリエイティブ監査の実測・v0.25.4344)。
//
// ★焼き方:
//   ①**芯は白く、外縁に素材の色相を残す**(明るいほど白へ寄せる)。ベタ1色にしない。
//   ②**αは明るさの0.78乗×1.15**。初版は 0.45乗×1.9 で焼いていたが、それは
//     **可視部の47〜69パーセントを完全不透明に潰す**=炎ではなく「縁だけボケた単色の塊」だった
//     (元素材の飽和は可視部の1〜23パーセント)。明るさは潰して稼がず、**同時に出す光源**で稼ぐ。
//   ③縮小はプリマルチプライしてから。④外接矩形ではなく**明るさの重心**(1133,556)を中心に 1000px角で切る
//     ("Side"=横殴りの素材で絵が片側に寄っており、矩形中心だと裏に敷いた時に脇へずれて見える)。
export const SKILL_BURST_FRAMES = 13;
/** 尺。素材の明るい本体は頭の3コマに集中しているので、長く引っ張らない。 */
export const SKILL_BURST_MS = 460;

/**
 * 進行度 t(0..1)→ コマ番号。**等間隔で送らない**(v0.25.4344)。
 * 実測でαの総量は f00→f05 で1/5まで落ちる=**頭の3コマが絵の本体**。等分送りだと
 * 本体が最初の1割で終わり、残りは薄い煙を見せるだけになるので、**頭を伸ばして尻を詰める**。
 * `t^1.7` で前半を引き伸ばす(=同じ尺のまま、衝撃のコマを長く見せる)。
 */
export const skillBurstFrame = (t: number): number => {
  const u = Math.pow(Math.min(1, Math.max(0, t)), 1.7);
  return Math.min(SKILL_BURST_FRAMES - 1, Math.max(0, Math.floor(u * SKILL_BURST_FRAMES)));
};

/** コマ番号 → テクスチャ名。 */
export const skillBurstTexture = (frame: number): string =>
  `fx/skill-burst-${String(Math.min(SKILL_BURST_FRAMES - 1, Math.max(0, frame))).padStart(2, '0')}`;

/**
 * レベル → 表示高さ(world px)。**社長指示「大きさがレベル」「一番小さくてもプレイヤーより大きく」**。
 * プレイヤーの描画は約64×52pxなので、最小の 150 でも縦で約3倍ある。
 */
export const skillBurstSize = (lv: number): number =>
  lv >= 3 ? 260 : lv === 2 ? 200 : 150;

/**
 * レア度 → 色(tint)。**社長指示「色がレア度 白、青、金」**。
 * ★赤と紫は使わない(CLAUDE.md の色の文法: 赤=カウンター対象 / 紫=カウンター不可)。
 * ★白は**冷たい白**、金は**濃い琥珀**にして3色を色相環で散らす(v0.25.4344)。
 * 淡い金(0xffd27a)は加算で芯が白へ飛び、0.25秒の一瞬では白と見分けが付かなかった。
 */
export const skillBurstTint = (rarity: 'normal' | 'rare' | 'super'): number =>
  rarity === 'super' ? 0xffb020 : rarity === 'rare' ? 0x7fb8ff : 0xdfe6f0;

/** 出だしの押し出し(慣性)。0.78→行き過ぎ→整定。等速で出て止まる形にしない。 */
export const skillBurstScale = (t: number): number => {
  if (t < 0.10) return 0.78 + 0.42 * (1 - Math.pow(1 - t / 0.10, 2)); // 加速して行き過ぎる
  if (t < 0.30) return 1.20 - 0.20 * (1 - Math.pow(1 - (t - 0.10) / 0.20, 2)); // 減速して整定
  return 1;
};

/**
 * α。末尾のランプ(素材任せにしない。最後の18パーセントで抜く)に加えて、**天井を 0.72 に置く**。
 * ★加算合成では α=1 だと素材の濃い所が全部クリップして**平たい1色の塊**になる(実画面で確認・
 * v0.25.4344)。せっかく階調を残して焼いても、出す側で飽和させたら同じこと。天井を下げると
 * 芯と外縁の差が残り、色(白/青/金)も濁らずに乗る。
 */
export const skillBurstAlpha = (t: number): number =>
  0.72 * (t < 0.82 ? 1 : Math.max(0, 1 - (t - 0.82) / 0.18));
