// 空中移動(ジャンプ/飛び掛かり/連続ジャンプ/滑空)の補間(v0.25.3076)。
//
// 社長指示「滑空はとにかくカクカクした動きを無くしたい」→「滑空って全てのジャンプね」。
// 跳ぶ技は**5経路すべてが等速の線形補間**(t をそのまま掛ける)で書かれていた。線形だと
// 飛び出しの瞬間に速度0→最高速、着地の瞬間に最高速→0と**速度が段差になる**ので、
// どれだけ滞空時間を伸ばしてもカクついて見える。
//
// ここは smootherstep(t³(6t²−15t+10))を使う。**両端で速度も加速度も0**になる曲線なので、
// 飛び出しと着地の角が消える(smoothstepより高次で、加速度の段差も出ない)。
//
// 掟: これは**移動の見た目の配分**だけを変える関数。滞空時間・着地点・着地の当たり判定は
// 呼び出し側が持つ値のままで、t=0で始点・t=1で終点に**必ず**一致する(=着地位置は1pxも動かない)。
export const airHopEase01 = (t: number): number => {
  const x = t <= 0 ? 0 : t >= 1 ? 1 : t;
  return x * x * x * (x * (x * 6 - 15) + 10);
};

/** airHopEase01 の微分(進行度あたり)。実際の速度 = 距離 × これ ÷ 滞空秒数。 */
export const airHopEaseD01 = (t: number): number => {
  const x = t <= 0 ? 0 : t >= 1 ? 1 : t;
  return 30 * x * x * (1 - x) * (1 - x);
};
