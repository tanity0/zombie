// 高さ(浮き)の曲線。
// v0.25.3077「フワッ……ダン!」(非対称3拍)は、社長指示v0.25.3273「ジャンプは綺麗に弧を描くように」で
// **上書き**され、左右対称の綺麗な放物線 h = 1-(2t-1)^2 に戻した(頂点t=0.5・両端で接地・
// 速度は連続=角が出ない)。滞空時間・着地点・判定は従来どおり呼び出し側の値のまま。
// 旧3拍カーブに戻す場合は git 履歴のこのファイル(v0.25.3272以前)を参照。
export const AIR_HOP_RISE_END = 0.5;   // 頂点(対称放物線=中央)。旧値0.26はv0.25.3273で廃止
export const AIR_HOP_FALL_START = 0.5; // 同上(滞空区間は無し=放物線)
export const airHopHeight01 = (t: number): number => {
  const x = t <= 0 ? 0 : t >= 1 ? 1 : t;
  const c = 2 * x - 1;
  return 1 - c * c; // 綺麗な放物線(h(0)=0 / h(0.5)=1 / h(1)=0)
};
