// 旧版は BASE_SOLDIERS(フォールバック側)の口調で書いたため、同じ出撃で同じ男が二つの声で喋った(チェンは軍師↔無線オペ・
// ムハンマドは四字熟語の丁寧語↔荒くれ・ローレンは明るい↔ぼやき・エリザベスは「ですわ」が消える)。ここは**バリアント側の声**に揃える。
//  - エドガー=前線の指揮官(「！」と短い命令) / ジョセフ=軽口 / エリザベス=「〜ですわ」「〜いたします」 / 武蔵=古風で一語
//  - ムハンマド=四字熟語の丁寧語(です/ます) / チェン=軍師(「僕の盤面」「ふっ/ふふ」) / ローレン=明るい口語 / フェイザー=ぶっきらぼう(「チッ」「触るな」)
// ★8人×全場面を同じ長さで埋めない。**喋らない人を作る**(未登録=何も出さない=無言)。
//   ・倒れた瞬間は息・断片か無言(倒れた男が自分の転倒を実況しない)。人格は「起こしてもらった」側に寄せる。
//   ・自力で起きた時は無言(store が silent を渡す)。この台帳は起こされた時の言葉だけ持つ。
//   ・「ボスの赤い予告が自分に掛かった」はカテゴリCD(gameStore ESCORT_TARGETED_CAT_CD_MS)を通るので、全員は喋らない。
//   ・★言い切りの「。」を基本に、「……」(息の途切れ)は全体で数本だけ(全員が同じ呼吸で喋らない=DC-1 #22)。
//   ・★存在しない挙動を約束しない(軍人に回避行動は無い=「回避に移る」は言わない=DC-1 #23)。危機の反応は短く(DC-1 #24)。
// 名簿 soldierIndex: 0 エドガー / 1 ジョセフ / 2 エリザベス / 3 武蔵 / 4 ムハンマド / 5 チェン / 6 ローレン / 7 フェイザー。
// ★・矢印・内部語は入れない(research/TEXT_REWRITE_2026-10.md の3項)。
export type EscortScene = 'downed' | 'revived' | 'targeted';

