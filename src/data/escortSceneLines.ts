    2: '失礼いたしましたわ。もう、大丈夫',        // エリザベス: 「ですわ」の丁寧語
    3: 'かたじけない。',                           // 武蔵: 一語
    4: 'ご助力、痛み入ります！まだ立てます！',     // ムハンマド: です/ます+四字熟語の系統(rescued「勇猛果敢……」)
    5: '助かったよ。盤面はまだ僕のものだ',         // チェン: pushback「まだ僕の盤面だ」
    6: 'ありがと！ちょっと休んだだけ！',           // ローレン: rescued「ありがと！ほんと助かった」
