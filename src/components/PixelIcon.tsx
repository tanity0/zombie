interface PixelIconProps {
  name: PixelIconName;
  /** 表示サイズ(px)。12の倍数だと格子が割り切れて一番きれい(12/24/36)。既定 16。 */
  size?: number;
  className?: string;
  /** 省くと currentColor(親の文字色に従う)。 */
  color?: string;
  title?: string;
}

// パターンごとの rect 列は1度だけ作ってキャッシュ(毎レンダーで文字列を舐めない)。
const RECT_CACHE = new Map<PixelIconName, Array<[number, number]>>();
const rectsFor = (name: PixelIconName): Array<[number, number]> => {
  let r = RECT_CACHE.get(name);
  if (!r) {
    r = [];
    const rows = PATTERNS[name];
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) if (row[x] === '#') r.push([x, y]);
    }
    RECT_CACHE.set(name, r);
  }
  return r;
};

export const PixelIcon: React.FC<PixelIconProps> = ({ name, size = 16, className = '', color, title }) => {
  const rects = rectsFor(name);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      className={`inline-block shrink-0 align-[-0.15em] ${className}`}
      fill={color ?? 'currentColor'}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title && <title>{title}</title>}
      {rects.map(([x, y]) => <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />)}
    </svg>
  );
};

export default PixelIcon;
